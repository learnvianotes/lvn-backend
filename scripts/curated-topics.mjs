#!/usr/bin/env node
/**
 * The curated subjects and topics (spec §4.1 "platform-curated + user-proposed"), taken from the /core catalog that
 * lvn-web ships (content-build/catalog.json): each subject, each topic group as a parent topic, and each topic under its
 * group. Writes a migration that inserts them, with UUIDv7 ids derived from the slugs so a re-run gives the same SQL.
 *
 *   node scripts/curated-topics.mjs ../lvn-web/content-build/catalog.json prisma/migrations/<timestamp>_curated_topics
 */
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const [catalogPath, outDir] = process.argv.slice(2)
if (!catalogPath || !outDir) throw new Error('usage: curated-topics.mjs <catalog.json> <migration dir>')

const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'))
// A fixed moment, so ids sort by subject and topic order and never change between runs.
const BASE_MS = Date.UTC(2026, 9, 8)
let tick = 0

/** UUIDv7 whose time is BASE_MS + tick and whose random bits come from the name. */
function idFor(name) {
  const ms = BASE_MS + tick++
  const b = createHash('sha256').update(name).digest().subarray(0, 16)
  b.writeUIntBE(ms, 0, 6)
  b[6] = 0x70 | (b[6] & 0x0f)
  b[8] = 0x80 | (b[8] & 0x3f)
  const h = b.toString('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`
}

const slugify = (s) => s.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60) || 'topic'
const q = (s) => `'${String(s).replace(/'/g, "''")}'`

const subjects = [...catalog.subjects].sort((a, b) => a.order - b.order)
const subjectRows = []
const topicRows = []
for (const [i, s] of subjects.entries()) {
  const subjectId = idFor(`subject:${s.id}`)
  subjectRows.push(`(${q(subjectId)}, ${q(s.id)}, ${q(s.title)}, ${i + 1})`)
  const topicSlugs = new Set(s.topics.map((t) => t.id))
  const groups = new Map()
  for (const [j, t] of s.topics.entries()) {
    let parentId = null
    if (t.group) {
      if (!groups.has(t.group)) {
        let slug = slugify(t.group)
        if (topicSlugs.has(slug)) slug = `${slug}-group`
        const groupId = idFor(`group:${s.id}/${slug}`)
        groups.set(t.group, groupId)
        topicRows.push(`(${q(groupId)}, ${q(subjectId)}, NULL, ${q(slug)}, ${q(t.group)}, ${groups.size})`)
      }
      parentId = groups.get(t.group)
    }
    topicRows.push(`(${q(idFor(`topic:${s.id}/${t.id}`))}, ${q(subjectId)}, ${parentId ? q(parentId) : 'NULL'}, ${q(t.id)}, ${q(t.title)}, ${j + 1})`)
  }
}

const sql = `-- Curated subjects and topics (spec §4.1), generated by scripts/curated-topics.mjs from lvn-web's /core catalog
-- (catalog ${catalog.version}, ${catalog.generatedAt}): ${subjectRows.length} subjects, ${topicRows.length} topics including topic groups.
-- Re-running the script on the same catalog gives the same ids; later catalog changes go in a new migration.

INSERT INTO "notes"."Subject" ("id", "slug", "title", "position") VALUES
${subjectRows.join(',\n')};

INSERT INTO "notes"."Topic" ("id", "subjectId", "parentId", "slug", "title", "position", "origin") SELECT v.id::uuid, v.subject::uuid, v.parent::uuid, v.slug, v.title, v.position, 'CURATED' FROM (VALUES
${topicRows.join(',\n')}
) AS v(id, subject, parent, slug, title, position);
`
mkdirSync(outDir, { recursive: true })
writeFileSync(path.join(outDir, 'migration.sql'), sql)
console.log(`${subjectRows.length} subjects, ${topicRows.length} topics → ${path.join(outDir, 'migration.sql')}`)
